"""ARGUS Unified Security Event Schema.

This is the central contract of ARGUS. Every event from every source
(Zeek, Suricata, future tools) gets normalized into this schema before
storage, analysis, or forwarding.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any, Optional

from pydantic import BaseModel, Field


def _generate_event_id() -> str:
    """Generate a unique event ID for ARGUS events."""
    return str(uuid.uuid4())


def _utc_now() -> datetime:
    """Generate current UTC timestamp."""
    return datetime.now(timezone.utc)


class ArgusEvent(BaseModel):
    """Normalized ARGUS security event.

    This is the unified schema that all security tool outputs are
    normalized into. It serves as the common language between:
    - Parsers (Zeek, Suricata)
    - Database (PostgreSQL / Supabase)
    - API (FastAPI endpoints)
    - ML models (future Phase 3)
    - AI Agent (future Phase 8)
    """

    # --- Identity ---
    event_id: str = Field(
        default_factory=_generate_event_id,
        description="Unique UUID generated by ARGUS for this event",
    )
    timestamp: datetime = Field(
        description="Normalized UTC timestamp of the event",
    )
    source: str = Field(
        description="Origin tool: 'zeek' or 'suricata'",
    )
    event_type: str = Field(
        description="Event type: 'connection', 'dns', 'alert', 'flow', etc.",
    )

    # --- Network 5-Tuple ---
    source_ip: Optional[str] = Field(
        default=None,
        description="Originating IP address (IPv4 or IPv6)",
    )
    source_port: Optional[int] = Field(
        default=None,
        ge=0,
        le=65535,
        description="Originating port number",
    )
    destination_ip: Optional[str] = Field(
        default=None,
        description="Destination IP address (IPv4 or IPv6)",
    )
    destination_port: Optional[int] = Field(
        default=None,
        ge=0,
        le=65535,
        description="Destination port number",
    )
    protocol: Optional[str] = Field(
        default=None,
        description="Network protocol: tcp, udp, icmp, etc.",
    )

    # --- Service / Application ---
    service: Optional[str] = Field(
        default=None,
        description="Application protocol: dns, http, ssl, etc.",
    )

    # --- Traffic Metrics ---
    duration: Optional[float] = Field(
        default=None,
        ge=0,
        description="Connection duration in seconds",
    )
    source_bytes: Optional[int] = Field(
        default=None,
        ge=0,
        description="Bytes sent by the source",
    )
    destination_bytes: Optional[int] = Field(
        default=None,
        ge=0,
        description="Bytes sent by the destination",
    )

    # --- Connection State ---
    connection_state: Optional[str] = Field(
        default=None,
        description="Connection state (Zeek conn_state or equivalent)",
    )

    # --- Threat Intelligence (populated by ML in Phase 3) ---
    attack_type: Optional[str] = Field(
        default=None,
        description="Attack classification label (null until ML is active)",
    )
    severity: Optional[int] = Field(
        default=None,
        ge=0,
        le=100,
        description="Severity / risk score 0-100 (null until ML is active)",
    )

    # --- Raw Data ---
    raw_event: Optional[dict[str, Any]] = Field(
        default=None,
        description="Original raw event from the source tool as a dictionary",
    )
    metadata: Optional[dict[str, Any]] = Field(
        default=None,
        description="Additional source-specific information",
    )

    # --- Record Tracking ---
    created_at: datetime = Field(
        default_factory=_utc_now,
        description="Timestamp when ARGUS ingested this event",
    )

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "event_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                    "timestamp": "2026-08-12T16:58:10Z",
                    "source": "zeek",
                    "event_type": "connection",
                    "source_ip": "192.168.1.100",
                    "source_port": 54993,
                    "destination_ip": "10.0.0.1",
                    "destination_port": 53,
                    "protocol": "udp",
                    "service": "dns",
                    "duration": 0.000963,
                    "source_bytes": 28,
                    "destination_bytes": 56,
                    "connection_state": "SF",
                    "attack_type": None,
                    "severity": None,
                }
            ]
        }
    }


class ArgusEventResponse(BaseModel):
    """API response wrapper for a single event."""

    event: ArgusEvent


class ArgusEventListResponse(BaseModel):
    """API response wrapper for a list of events."""

    events: list[ArgusEvent]
    total: int


class AnalysisResult(BaseModel):
    """Placeholder response for the /analyze endpoint.

    In Phase 3, this will contain actual ML results:
    - anomaly_score
    - attack_classification
    - risk_score
    """

    event_id: str
    status: str = "ml_not_implemented"
    message: str = "ML analysis will be available in Phase 3"
    anomaly_score: Optional[float] = None
    attack_type: Optional[str] = None
    risk_score: Optional[int] = None
